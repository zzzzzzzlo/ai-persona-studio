async (page) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  const snap = async name => { await page.screenshot({ path: 'output/playwright/' + name + '.png', fullPage: true, animations: 'disabled' }); };
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('http://127.0.0.1:5173/pink.html');
  await page.evaluate(() => localStorage.removeItem('ai-heart-personality-v2'));
  await page.reload();
  await page.getByRole('button', { name: '开始测试', exact: true }).waitFor();
  await snap('v2-home');
  assert(await page.locator('.debug-panel').count() === 0, 'Debug must be hidden');
  await page.getByRole('button', { name: '开始测试', exact: true }).click();
  assert((await page.locator('.progress-caption').textContent()).includes('性格底色'), 'Stage 1 missing');
  await snap('v2-question-01');
  await page.locator('[data-answer="C"]').click();
  await page.waitForFunction(() => document.querySelector('.counter').textContent.startsWith('02'));
  await page.getByRole('button', { name: '返回上一题' }).click();
  assert(await page.locator('[data-answer="C"]').getAttribute('aria-pressed') === 'true', 'Previous choice lost');
  await page.locator('[data-answer="B"]').click();
  await page.waitForFunction(() => document.querySelector('.counter').textContent.startsWith('02'));
  await page.reload();
  await page.locator('[data-answer="A"]').waitFor();
  assert((await page.locator('.counter').textContent()).startsWith('02'), 'Quiz index did not restore');
  const answers = ['B'];
  for (let i = 1; i < 14; i++) {
    const expected = String(i + 1).padStart(2, '0');
    assert((await page.locator('.counter').textContent()).startsWith(expected), 'Wrong question sequence');
    await page.locator('[data-answer="A"]').click(); answers.push('A');
    if (i === 6) assert((await page.locator('.progress-caption').textContent()).includes('相处方式'), 'Stage 2 missing');
    if (i < 13) await page.waitForFunction(n => document.querySelector('.counter').textContent.startsWith(n), String(i + 2).padStart(2, '0'));
  }
  await page.locator('.transition').waitFor();
  assert(await page.locator('.counter').count() === 0, 'Q15 must not appear before transition');
  await snap('v2-transition');
  await page.reload();
  await page.locator('.transition').waitFor();
  await page.getByRole('button', { name:'继续塑造 TA' }).click();
  assert((await page.locator('.counter').textContent()).startsWith('15'), 'Wrong Q15 index');
  assert((await page.locator('.progress-caption').textContent()).includes('AI 人格设定'), 'Stage 3 missing');
  await page.getByRole('button', { name:'返回上一题' }).click();
  await page.locator('.transition').waitFor();
  await page.getByRole('button', { name:'返回上一题' }).click();
  assert((await page.locator('.counter').textContent()).startsWith('14'), 'Transition back must show Q14');
  await page.locator('[data-answer="D"]').click(); answers[13]='D';
  await page.locator('.transition').waitFor();
  await page.getByRole('button', { name:'继续塑造 TA' }).click();
  assert(await page.locator('.answer').count() === 4, 'Q15 must have 4 configuration choices');
  assert((await page.locator('.counter').textContent()).includes('/ 18'), 'Real progress must be 18');
  await snap('v2-question-15');
  await page.locator('[data-answer="D"]').click();
  await page.waitForFunction(() => document.querySelector('.counter').textContent.startsWith('16'));
  await page.getByRole('button', { name:'返回上一题' }).click();
  assert(await page.locator('[data-answer="D"]').getAttribute('aria-pressed') === 'true', 'Q15 choice lost');
  await page.locator('[data-answer="B"]').click(); answers.push('B');
  await page.waitForFunction(() => document.querySelector('.counter').textContent.startsWith('16'));
  await page.reload();
  await page.locator('.counter').waitFor();
  assert((await page.locator('.counter').textContent()).startsWith('16'), 'Configuration refresh failed');
  for (const [index,choice] of ['B','B','A'].entries()) {
    await page.locator('[data-answer="' + choice + '"]').click(); answers.push(choice);
    if (index < 2) await page.waitForFunction(n => document.querySelector('.counter').textContent.startsWith(n), String(17 + index));
  }
  await page.locator('.analysis').waitFor();
  const analysisStart = Date.now();
  await page.waitForFunction(() => !document.querySelector('.prediction').hidden);
  await snap('v2-analysis');
  await page.locator('.result').waitFor();
  const elapsed = Date.now() - analysisStart;
  assert(elapsed >= 1650 && elapsed < 3500, 'Analysis duration out of range: ' + elapsed);
  const computed = await page.evaluate(expectedAnswers => {
    const A = window.HeartTest, saved = JSON.parse(localStorage.getItem(A.config.storageKey));
    return { saved, expected: A.evaluateAnswers(expectedAnswers), vector: A.score(expectedAnswers) };
  }, answers);
  assert(JSON.stringify(computed.saved.answers) === JSON.stringify(answers), 'Edited answers were not saved');
  assert((await page.locator('.persona-title').textContent()).includes(computed.expected.primary.name), 'Result does not match scoring');
  assert(await page.locator('.profile-item').count() === 4, 'AI profile missing');
  assert((await page.locator('[data-profile="G"]').textContent()).includes('适应型'), 'Formal Q16 B must produce the middle band');
  assert((await page.locator('[data-profile="R"]').textContent()).includes('轻剧情型'), 'Formal Q17 B must produce the middle band');
  assert((await page.locator('.result-hero .eyebrow').textContent()).includes('你的 AI 心动原型'), 'V2 heading missing');
  const expectedLabels = await page.evaluate(scores => window.HeartTest.buildAIProfile(scores).map(p=>p.label), computed.expected.aiScores);
  for (const label of expectedLabels) assert((await page.locator('.ai-profile').textContent()).includes(label), 'Wrong profile label ' + label);
  await snap('v2-result-flow');
  await page.locator('.ai-profile').screenshot({ path:'output/playwright/v2-ai-profile.png', animations:'disabled' });
  await page.getByRole('button', { name:'把 TA 真正捏出来' }).click();
  assert(await page.locator('#toast').textContent() === '专属 AI 定制版正在准备中。想参与内测，可以回到发布这份测试的笔记评论『想定制』；也可以先保存这份配置。', 'Customize invitation missing');
  const title = await page.locator('.persona-title').textContent();
  await page.reload(); await page.locator('.persona-title').waitFor();
  assert(await page.locator('.persona-title').textContent() === title, 'Result changed after refresh');
  await page.getByRole('button', { name: '保存我的心动人格卡' }).click();
  await page.getByRole('dialog').waitFor();
  assert(await page.locator('.share-card-image').evaluate(el => el.naturalWidth === 1080 && el.naturalHeight === 1440), 'Wrong share image dimensions');
  await snap('v2-share-browser');
  await page.locator('.share-card-image').screenshot({ path:'output/playwright/v2-share-card.png' });
  await page.keyboard.press('Escape');
  assert(await page.getByRole('dialog').count() === 0, 'Escape did not close dialog');
  assert(await page.getByRole('button', { name: '发到小红书', exact: true }).count() === 0, 'Publish button must be removed');
  await page.getByRole('button', { name: '重新测试', exact: true }).click();
  await page.getByRole('button', { name: '开始测试', exact: true }).waitFor();
  assert(await page.evaluate(() => localStorage.getItem('ai-heart-personality-v2') === null), 'Clear left saved record');
  await page.reload();
  assert(await page.getByRole('button', { name: '开始测试', exact: true }).count() === 1, 'Reset not persisted');
  assert(errors.length === 0, 'Browser errors: ' + errors.join('; '));
  return { passed: true, flow: '18 questions, three stages, Q14 transition/back/refresh, Q15 edit/refresh, personality + AI profile, CTA, share card, reset', analysisMs: elapsed, errors };
}
